type T = Textos<typeof es>;

/**
 * Textos que genera la web para la línea de tiempo de la ficha (los datos guardan la versión en castellano).
 * Los que no siguen un patrón conocido (cargos, trayectoria, altas y bajas comunicadas) se muestran tal cual.
 */
export function textoEvento(texto: string, lang: Idioma, t: T): string {
  if (lang === 'es') return texto;
  const g = (x: string[], fem: boolean) => x[fem ? 1 : 0];
  const docs: Record<string, string> = {
    'Declaración de bienes y rentas': t.docs.bienes,
    'Modificación de su declaración de bienes': t.docs.modificacionSu,
    'Declaración de intereses económicos': t.docs.intereses,
  };
  if (docs[texto]) return docs[texto];
  let m = texto.match(/^Adquiere la condición plena de diputad([oa]) en la ([IVXL]+) Legislatura$/);
  if (m) return f(g(t.tray.plena, m[1] === 'a'), { leg: m[2] });
  m = texto.match(/^Diputad([oa]) en la ([IVXL]+) Legislatura \(([^)]+)\)$/);
  if (m) return f(g(t.tray.legislatura, m[1] === 'a'), { leg: m[2], anios: m[3] });
  return texto;
}

/** Resumen de una declaración de bienes en la línea de tiempo («3 propiedades (2 viviendas) y 1 vehículo · deudas: …»). */
export function detalleEvento(detalle: string, lang: Idioma, t: T): string {
  if (lang === 'es') return detalle;
  const m = detalle.match(/^(\d+) propiedad(?:es)? \((\d+) viviendas?\) y (\d+) vehículos?(?: · deudas: (?:(sin préstamos declarados)|(\d+) préstamos? con ([\d.]+)\s?€ pendientes))?$/);
  if (!m) return detalle;
  const pal = comun[lang].palabras;
  let s = f(t.tray.resumen, { propiedades: pl(+m[1], pal.propiedades, lang), viviendas: pl(+m[2], pal.viviendas, lang), vehiculos: pl(+m[3], pal.vehiculos, lang) });
  if (m[4]) s += f(t.tray.deudas, { texto: t.tray.sinPrestamos });
  else if (m[5]) s += f(t.tray.deudas, { texto: pl(+m[5], t.tray.prestamos, lang, { eur: formatos(lang).eur(Number(m[6].replace(/\./g, ''))) }) });
  return s;
}
